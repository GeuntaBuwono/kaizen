// `bun run build:web`: bundles the notebook's script and CodeMirror into
// web/notebook.js, and the in-card terminal and xterm.js into web/term.js (+ its
// stylesheet, web/term.css), all committed, so an install or a checkout serves it with no
// install step and no network. The first line is a hash of what it was built from;
// cli/notes.test.ts fails when a committed file no longer matches.
import { createHash } from "node:crypto";
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";

const root = dirname(import.meta.dir);
const SOURCES = ["web/notebook.ts", "web/notes-lib.ts", "web/term.ts"];
export const OUT = join(root, "web", "notebook.js");
export const TERM_OUT = join(root, "web", "term.js");

// The sources and the exact dependency versions: a CodeMirror bump is a rebuild too.
export function sourceHash() {
  const h = createHash("sha256");
  for (const f of SOURCES) h.update(readFileSync(join(root, f), "utf8").replace(/\r\n/g, "\n"));
  h.update(JSON.stringify(JSON.parse(readFileSync(join(root, "package.json"), "utf8")).devDependencies ?? {}));
  return h.digest("hex").slice(0, 16);
}
export const banner = (what = "notebook", from = "web/notebook.ts") => `/* kaizen ${what} ${sourceHash()} -- generated by bun run build:web from ${from}; do not edit */`;

if (import.meta.main) {
  for (const [src, out, what] of [["web/notebook.ts", OUT, "notebook"], ["web/term.ts", TERM_OUT, "terminal"]] as const) {
    // The terminal is a classic script on the board's page: wrapped, or its top-level
    // names collide with the board's own globals and the whole file is refused.
    const r = await Bun.build({ entrypoints: [join(root, src)], target: "browser", minify: true, format: what === "terminal" ? "iife" : "esm" });
    if (!r.success) { for (const l of r.logs) console.error(l); process.exit(1); }
    writeFileSync(out, banner(what, src) + "\n" + await r.outputs[0]!.text());
    console.log(`  ${src.replace(".ts", ".js")}  ${(Bun.file(out).size / 1024).toFixed(0)} KB`);
  }
  copyFileSync(join(root, "node_modules", "@xterm", "xterm", "css", "xterm.css"), join(root, "web", "term.css"));
}
